import type { Speaker } from '@/types/reservation'

export interface DemoScriptLine {
  speaker: Speaker
  text: string
}

export interface DemoScript {
  id: number
  type: string
  /** 접수 시각. "내일/모레" 변환 기준이 된다. */
  receivedAt: string
  lines: DemoScriptLine[]
}

function parseScript(
  id: number,
  type: string,
  receivedAt: string,
  raw: string,
): DemoScript {
  const lines = raw.split(' / ').map((segment) => {
    const idx = segment.indexOf(':')
    const who = segment.slice(0, idx).trim()
    const text = segment.slice(idx + 1).trim()
    const speaker: Speaker = who === '어르신' ? '고객' : '상담원'
    return { speaker, text }
  })
  return { id, type, receivedAt, lines }
}

